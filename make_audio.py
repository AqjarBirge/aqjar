async def main():
    args = [a.lower() for a in sys.argv[1:]]
    lang = "ru" if "ru" in args else "kz"
    gender = "male" if "male" in args else "female"
    voice = VOICES[(lang, gender)]
    os.makedirs("audio", exist_ok=True)
    for i, text in enumerate(TEXTS[lang]):
        path = os.path.join("audio", f"{lang}-{i}.mp3")
        await edge_tts.Communicate(text, voice, rate="+5%").save(path)
        print("готово:", path)
    print("Всё. Папка audio должна лежать рядом с app.html.")


if __name__ == "__main__":
    asyncio.run(main())
